//! Independent TEST oracle: own formulas/rules, backward demands and literal rows.
//! Not a production implementation, external gold, or independently authored corpus.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum Formula {
    Atom(u8),
    And(Vec<Formula>),
    Not(Box<Formula>),
    Or(Vec<Formula>),
}
#[derive(Clone, Debug)]
pub enum Rule {
    Given(usize),
    Child(usize, usize),
    Join(Vec<usize>),
}
#[derive(Clone, Debug)]
pub struct Step {
    pub conclusion: Formula,
    pub rule: Rule,
}
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum BadShape {
    Empty,
    Reference,
    Depth,
    Arity,
}
pub fn p() -> Formula {
    Formula::Atom(0)
}
pub fn q() -> Formula {
    Formula::Atom(1)
}
pub fn r() -> Formula {
    Formula::Atom(2)
}
pub fn pq() -> Formula {
    Formula::And(vec![p(), q()])
}
pub fn qr() -> Formula {
    Formula::And(vec![q(), r()])
}
pub fn e_trace(goal_q: bool, wrong: bool) -> Vec<Step> {
    let goal = if goal_q { q() } else { p() };
    let correct = usize::from(goal_q);
    vec![
        Step {
            conclusion: pq(),
            rule: Rule::Given(0),
        },
        Step {
            conclusion: goal,
            rule: Rule::Child(0, if wrong { 1 - correct } else { correct }),
        },
    ]
}
pub fn t_trace() -> Vec<Step> {
    vec![
        Step {
            conclusion: pq(),
            rule: Rule::Given(0),
        },
        Step {
            conclusion: q(),
            rule: Rule::Child(0, 1),
        },
        Step {
            conclusion: r(),
            rule: Rule::Given(1),
        },
        Step {
            conclusion: qr(),
            rule: Rule::Join(vec![1, 2]),
        },
    ]
}
/// Demand each recorded conclusion backward, including unreachable/unused steps.
/// No production AST lowering, evaluator, certificate checker or program call.
pub fn check(gamma: &[Formula], goal: &Formula, proof: &[Step]) -> Result<bool, BadShape> {
    if proof.is_empty() {
        return Err(BadShape::Empty);
    }
    if proof.last().map(|s| &s.conclusion) != Some(goal) {
        return Ok(false);
    }
    for (index, step) in proof.iter().enumerate() {
        if !demand(gamma, proof, index, &step.conclusion, 0)? {
            return Ok(false);
        }
    }
    Ok(true)
}
fn demand(
    gamma: &[Formula],
    proof: &[Step],
    index: usize,
    wanted: &Formula,
    depth: usize,
) -> Result<bool, BadShape> {
    if depth > 64 {
        return Err(BadShape::Depth);
    }
    let step = proof.get(index).ok_or(BadShape::Reference)?;
    if &step.conclusion != wanted {
        return Ok(false);
    }
    match &step.rule {
        Rule::Given(premise) => Ok(gamma.get(*premise).ok_or(BadShape::Reference)? == wanted),
        Rule::Child(parent, child) => {
            if *parent >= index {
                return Err(BadShape::Reference);
            }
            let previous = proof.get(*parent).ok_or(BadShape::Reference)?;
            let Formula::And(children) = &previous.conclusion else {
                return Ok(false);
            };
            let actual = children.get(*child).ok_or(BadShape::Reference)?;
            Ok(actual == wanted && demand(gamma, proof, *parent, &previous.conclusion, depth + 1)?)
        }
        Rule::Join(priors) => {
            let Formula::And(children) = wanted else {
                return Ok(false);
            };
            if priors.len() != children.len() || priors.is_empty() {
                return Err(BadShape::Arity);
            }
            for (prior, child) in priors.iter().zip(children) {
                if *prior >= index {
                    return Err(BadShape::Reference);
                }
                if !demand(gamma, proof, *prior, child, depth + 1)? {
                    return Ok(false);
                }
            }
            Ok(true)
        }
    }
}
// Literal hand rows (p,q)=00,10,01,11; not generated by an evaluator.
pub const E_GAMMA: [bool; 4] = [false, false, false, true];
pub const E_P: [bool; 4] = [false, true, false, true];
pub const E_Q: [bool; 4] = [false, false, true, true];
// (p,q,r)=000,100,010,110,001,101,011,111.
pub const T_GAMMA: [bool; 8] = [false, false, false, false, false, false, false, true];
pub const T_QR: [bool; 8] = [false, false, false, false, false, false, true, true];
pub fn literal_entails<const N: usize>(gamma: [bool; N], goal: [bool; N]) -> bool {
    gamma.into_iter().zip(goal).all(|(g, p)| !g || p)
}
