//! Synthetic authenticated fixtures exercise only the public host API.
#![forbid(unsafe_code)]

use lc631_core::{
    stable_sha256, Action, ArtifactId, AuthorityRevision, DeonticPolarity, ExecutionPermit,
    SourceSpan, TurnId,
};
use lc631_host::{
    host_seed_scoped_payload_digest, HostError, HostReceiptContext, HostSeedEnvelope,
};
use lc631_receipt_kernel::{ReceiptClass, ReceiptScope, ReplayGuard, SubjectRevision};
use std::fs;
use std::path::PathBuf;
use std::sync::atomic::{AtomicU64, Ordering};
use std::time::{SystemTime, UNIX_EPOCH};

const SCOPE: &str = "fixture/file";
const ARTIFACT: ArtifactId = ArtifactId(7);
const TURN: TurnId = TurnId(9);

fn fixture_root() -> PathBuf {
    static SERIAL: AtomicU64 = AtomicU64::new(0);
    let time = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap()
        .as_nanos();
    let root = std::env::temp_dir().canonicalize().unwrap().join(format!(
        "beta7-host-scope-{}-{time}-{}",
        std::process::id(),
        SERIAL.fetch_add(1, Ordering::Relaxed),
    ));
    fs::create_dir(&root).unwrap();
    root
}

fn local_host() -> HostReceiptContext {
    // Public synthetic fixture material only. No installed key is read/generated.
    let root = fixture_root();
    fs::write(root.join("receipt-root-v1.key"), "ab".repeat(32)).unwrap();
    HostReceiptContext::load_existing(&root).unwrap()
}

fn scoped_seed(host: &HostReceiptContext, text: &str) -> HostSeedEnvelope {
    let whole = SourceSpan::checked(text, 0, text.len()).unwrap();
    let wire = host
        .issuer()
        .issue(
            ReceiptClass::HostSeed,
            SubjectRevision::checked(stable_sha256(text)).unwrap(),
            ReceiptScope::checked(format!("host/user-span/7/9/{}", stable_sha256(SCOPE))).unwrap(),
            host_seed_scoped_payload_digest(ARTIFACT, TURN, text, whole, SCOPE),
            100,
            Some(200),
            None,
        )
        .unwrap();
    HostSeedEnvelope::verify_attested_scoped(
        ARTIFACT,
        TURN,
        text.into(),
        whole,
        SCOPE.into(),
        wire,
        host.verifier(),
        &mut ReplayGuard::default(),
        100,
    )
    .unwrap()
}

fn span(text: &str, excerpt: &str) -> SourceSpan {
    let start = text.find(excerpt).unwrap();
    SourceSpan::checked(text, start, start + excerpt.len()).unwrap()
}

fn issue(
    host: &HostReceiptContext,
    seed: &HostSeedEnvelope,
    selected: SourceSpan,
) -> Result<ExecutionPermit, HostError> {
    host.issue_execution_permit(
        seed,
        Action::Edit,
        DeonticPolarity::Grant,
        selected,
        SCOPE.into(),
        AuthorityRevision(4),
        120,
        150,
        0,
        &mut ReplayGuard::default(),
    )
}

#[test]
fn beta7_host_negative_clause_cannot_grant_from_its_selected_action() {
    let host = local_host();
    let action = "edit this file";
    let affirmative = scoped_seed(&host, action);
    let actual = issue(&host, &affirmative, span(action, action)).unwrap();
    assert_eq!(actual.source_span(), span(action, action));

    let text = "Do not edit this file.";
    let denied = scoped_seed(&host, text);
    assert_eq!(
        issue(&host, &denied, span(text, action)),
        Err(HostError::AuthoritySourceIneligible),
        "selecting the identical action must retain its negating clause",
    );
}
